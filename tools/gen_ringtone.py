#!/usr/bin/env python3
"""Generate the Space Harrier (Japanese Sega Master System / Mark III BIOS) ringtone.

The Japanese SMS BIOS plays an FM arrangement of Hiroshi Miyauchi's Space Harrier
theme on boot. Note data is derived from the fan MIDI sequence of that BIOS demo by
João "Johnnyz" Buaes (vgmusic.com, JBIOS-Demo.mid), which this script downloads.

The watch has a single piezo buzzer, so chords in the opening fanfare are rendered as
fast arpeggios (the classic PSG trick) and the melody is played as a single voice,
two octaves up where the piezo is loudest.

Usage: gen_ringtone.py <JBIOS-Demo.mid> > ../main/src/Services/Ringtones.inc
"""
import struct
import sys

LEAD, HARM1, HARM2 = 2, 5, 6     # tracks: lead, two harmony voices
TRANSPOSE = 24                   # semitones
ARP_MS = 25                      # arpeggio step
GAP_MS = 18                      # silence before re-striking the same note


def vlq(d, i):
    v = 0
    while True:
        b = d[i]
        i += 1
        v = (v << 7) | (b & 0x7f)
        if not b & 0x80:
            return v, i


def parse(path):
    d = open(path, 'rb').read()
    _, ntrk, div = struct.unpack('>HHH', d[8:14])
    i, tracks, tempo = 14, [], 500000
    for _ in range(ntrk):
        ln = struct.unpack('>I', d[i + 4:i + 8])[0]
        j, end, i = i + 8, i + 8 + ln, i + 8 + ln
        tick, run, notes, on = 0, None, [], {}
        while j < end:
            dt, j = vlq(d, j)
            tick += dt
            st = d[j]
            if st == 0xff:
                typ = d[j + 1]
                l, k = vlq(d, j + 2)
                if typ == 0x51:
                    tempo = int.from_bytes(d[k:k + l], 'big')
                j = k + l
                continue
            if st in (0xf0, 0xf7):
                l, k = vlq(d, j + 1)
                j = k + l
                continue
            if st & 0x80:
                run, j = st, j + 1
            ev = run & 0xf0
            if ev in (0xc0, 0xd0):
                j += 1
                continue
            a, b = d[j], d[j + 1]
            j += 2
            if ev == 0x90 and b > 0:
                on[a] = tick
            elif (ev == 0x80 or ev == 0x90) and a in on:
                notes.append((on.pop(a), tick, a))
        tracks.append(sorted(notes))
    return div, tempo, tracks


def freq(n):
    return round(440 * 2 ** ((n + TRANSPOSE - 69) / 12))


def main():
    div, tempo, tracks = parse(sys.argv[1])
    ms_per_tick = tempo / 1000 / div
    lead = tracks[LEAD]

    # The fanfare ends where the lead first drops below C5. The full fanfare is ~25 s, so
    # the ringtone keeps its first two chord stabs, its closing run-up, then the first
    # 4 bars of the main theme.
    bar = div * 4
    melody_start = next(s for s, e, n in lead if n < 72)
    sections = [(0, 2 * bar), (melody_start - 2 * bar, melody_start), (melody_start, melody_start + 4 * bar)]

    out = []

    def emit(f, ms):
        ms = int(round(ms))
        if ms <= 0:
            return
        if out and out[-1][0] == f:
            out[-1][1] += ms
        else:
            out.append([f, ms])

    # Fanfare: arpeggiate whatever lead + harmony notes sound in each slice
    voices = [tracks[LEAD], tracks[HARM1], tracks[HARM2]]
    for sec_start, sec_end in sections[:2]:
        render_chords(voices, sec_start, sec_end, ms_per_tick, emit)

    # Melody, single voice
    sec_start, sec_end = sections[2]
    pos = sec_start
    for s, e, n in lead:
        if s < sec_start or s >= sec_end:
            continue
        if s > pos:
            emit(0, (s - pos) * ms_per_tick)
        emit(0, GAP_MS)
        emit(freq(n), (min(e, sec_end) - s) * ms_per_tick - GAP_MS)
        pos = e
    emit(0, 600)  # breath before the loop restarts

    print_table(out)


def render_chords(voices, start, end, ms_per_tick, emit):
    bounds = sorted({t for v in voices for s, e, n in v if s < end and e > start
                     for t in (max(s, start), min(e, end))} | {start, end})
    for a, b in zip(bounds, bounds[1:]):
        chord = sorted({n for v in voices for s, e, n in v if s <= a < e}, reverse=True)
        dur = (b - a) * ms_per_tick
        if not chord:
            emit(0, dur)
            continue
        # short gap when the chord is re-struck, so repeated stabs stay articulated
        restrike = any(s == a for v in voices for s, e, n in v)
        if restrike:
            emit(0, GAP_MS)
            dur -= GAP_MS
        t, k = 0, 0
        while t + 1 < dur:
            step = min(ARP_MS, dur - t)
            emit(freq(chord[k % len(chord)]), step)
            t += step
            k += 1



def print_table(out):
    total = sum(ms for _, ms in out)
    print('// Generated by tools/gen_ringtone.py - do not edit.')
    print('// Space Harrier theme (Hiroshi Miyauchi), as played by the Japanese Sega Master System BIOS.')
    print(f'// {len(out)} tones, {total / 1000:.1f} s')
    print('static const Chirp SpaceHarrierRing[] = {')
    for i in range(0, len(out), 6):
        print('\t' + ' '.join(f'{{ {f}, {f}, {ms} }},' for f, ms in out[i:i + 6]))
    print('};')


if __name__ == '__main__':
    main()
